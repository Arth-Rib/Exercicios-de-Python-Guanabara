n1=int(input('Digite uma valor:'))
n2=int(input('Digite outro valor:'))
print('A soma de {} e {} vale {}'.format(n1,n2,n1+n2))
print('A subtração de {} e {} vale {}'.format(n1,n2,n1-n2))
print('A multiplicação entre {} e {} vale {}'.format(n1,n2,n1*n2))
print('A divisão entre {} e {} vale {}'.format(n1,n2,n1/n2))
print('O resto da divisão entre {} e {} vale {}'.format(n1,n2,n1%n2))
print('O valor de {} elevado a {} vale {}'.format(n1,n2,n1**n2))

